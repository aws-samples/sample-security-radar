def test_analyze_station_only_reanalyses_changed_p0_p1(env, monkeypatch):
    h, s3 = env
    _put(s3, "raw/2026-10-23/2026-10-23T04:00:00Z/bleepingcomputer.jsonl", "fresh")
    h.process({})
    calls, digests = [], []
    def fake(prompt, model, max_tokens):
        (digests if "daily security digest" in prompt else calls).append(model)
        if "daily security digest" in prompt:
            eid = h._store.events_updated_since("2026-10-01")[0].event_id
            return h_llm.LlmResult("ok", json.dumps({"summary": [{"text": "x", "cite": [eid]}]}), {}, model, 0.1)
        return h_llm.LlmResult("ok", '{"bluf":[{"text":"x","cite":[]}]}', {}, model, 0.1)
    from radar import llm as h_llm
    monkeypatch.setattr(h_llm, "converse", fake)
    out1 = h.analyze_events({"changed": []})
    out2 = h.analyze_events({"changed": []})
    assert len(out1["changed"]) == 1 and len(calls) == 1      # the P0 event is analysed once
    assert out2["changed"] == [] and len(calls) == 1          # unchanged evidence ⇒ no second call
    # C7: 12:30 HKT ⇒ the day's digest is written once (status ok) and not regenerated by the next cycle
    d = h._store.get_source_state(h.DIGEST_KEY)
    assert len(digests) == 1 and d["status"] == "ok" and d["day"] == "2026-10-23" and d["header"]["events"] == 1 and d["summary"][0]["grounded"]


