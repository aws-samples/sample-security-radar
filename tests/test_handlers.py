def _put(s3, key, title):
    raw = {"source_id": "bleepingcomputer", "url": f"https://b.example/{title}", "title": title,
           "text": "CVE-2026-7777 exploited in the wild", "published_at": "2026-10-23T01:00:00Z",
           "guid": None, "author": None, "links": [], "extra": {}}
    s3.put_object(Bucket="raw", Key=key, Body=json.dumps(raw).encode())


def test_process_picks_up_batches_left_by_a_failed_cycle(env):
    h, s3 = env
    _put(s3, "raw/2026-10-23/2026-10-23T04:00:00Z/bleepingcomputer.jsonl", "left-over")
    _put(s3, "raw/2026-10-23/2026-10-23T04:30:00Z/bleepingcomputer.jsonl", "fresh")
    out = h.process({"results": []})  # the payload no longer matters: pending batches come from S3
    assert len(out["changed"]) == 1
    assert h._pending_raw_keys(timeutil.now()) == []
    again = h.process({"results": []})
    assert again["changed"] == []


